/**
 * Writes the network security config, and with it the shop's certificate authority when this PC
 * has one. ruzzco-system's `npm run https` creates that authority in web/certs/ to serve
 * https://<PC address>:3443. Trusting it lets the app use that address, where the pages open
 * without the shop PC. Only the public certificate is copied, never the key.
 */
abstract class ShopTrustTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val caFile: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        val ca = caFile.files.firstOrNull { it.isFile }
        var shopAnchor = ""
        if (ca != null) {
            val pem = ca.readText()
            require("BEGIN CERTIFICATE" in pem && "PRIVATE KEY" !in pem) {
                "$ca is not a certificate on its own. Point ruzzco.shopCa at ruzzco-ca.cert.pem."
            }
            File(out, "raw").mkdirs()
            File(out, "raw/shop_ca.pem").writeText(pem)
            shopAnchor = "\n            <certificates src=\"@raw/shop_ca\" />"
        } else {
            logger.warn("No shop certificate at ${caFile.files.firstOrNull()}: the app can open https://…:3443 only on phones that have it installed.")
        }
        File(out, "xml").mkdirs()
        File(out, "xml/network_security_config.xml").writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by the shopTrust task in app/build.gradle.kts. -->
            |<network-security-config xmlns:tools="http://schemas.android.com/tools">
            |    <!-- Plain HTTP stays allowed: the shop PC also serves http://<PC address>:3000, and a
            |         specific domain can't be named because it is a LAN address that differs per shop. -->
            |    <base-config cleartextTrafficPermitted="true" tools:ignore="InsecureBaseConfiguration,AcceptsUserCertificates">
            |        <trust-anchors>
            |            <certificates src="system" />
            |            <!-- Certificates installed on the phone, as Chrome trusts them: another shop PC's. -->
            |            <certificates src="user" />$shopAnchor
            |        </trust-anchors>
            |    </base-config>
            |</network-security-config>
            |""".trimMargin()
        )
    }
}

val shopTrust = tasks.register<ShopTrustTask>("shopTrust") {
    caFile.from(providers.gradleProperty("ruzzco.shopCa")
        .orElse(rootProject.file("../web/certs/ruzzco-ca.cert.pem").path))
    outputDir.set(layout.buildDirectory.dir("generated/shopTrust"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(shopTrust, ShopTrustTask::outputDir)
    }
}

